"""
Generate 10 real knowledge .docx documents for Lingshan scenic area.
Uses << >> as placeholders for Chinese curly quotes (replaced at runtime).
Run: python data/scripts/generate_docs.py
Output: data/raw/*.docx
"""
import os, sys
from docx import Document
from docx.shared import Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

OUT_DIR = os.path.join(os.path.dirname(__file__), "..", "raw")
os.makedirs(OUT_DIR, exist_ok=True)

# Chinese curly quotation marks
LQ = '“'  # left "
RQ = '”'  # right "

def q(s):
    """Replace << and >> placeholders with proper Chinese curly quotes."""
    return s.replace('<<', LQ).replace('>>', RQ)

def make_doc(title, author="灵境云游知识库"):
    doc = Document()
    sec = doc.sections[0]
    sec.page_width = Cm(21)
    sec.page_height = Cm(29.7)
    sec.top_margin = Cm(2.54)
    sec.bottom_margin = Cm(2.54)
    sec.left_margin = Cm(3.18)
    sec.right_margin = Cm(3.18)
    h = doc.add_heading(q(title), level=0)
    h.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for r in h.runs:
        r.font.size = Pt(22)
        r.font.color.rgb = RGBColor(0x1a, 0x1a, 0x2e)
    meta = doc.add_paragraph()
    meta.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = meta.add_run(q(f"来源：{author}  |  仅供灵境云游AI导览系统内部使用"))
    run.font.size = Pt(9)
    run.font.color.rgb = RGBColor(0x99, 0x99, 0x99)
    doc.add_paragraph("")
    return doc

def add_h1(doc, text):
    h = doc.add_heading(q(text), level=1)
    for r in h.runs:
        r.font.size = Pt(16)
        r.font.color.rgb = RGBColor(0x1a, 0x1a, 0x2e)

def add_h2(doc, text):
    h = doc.add_heading(q(text), level=2)
    for r in h.runs:
        r.font.size = Pt(13)
        r.font.color.rgb = RGBColor(0x33, 0x33, 0x55)

def add_para(doc, text):
    p = doc.add_paragraph()
    p.style = doc.styles['Normal']
    p.paragraph_format.line_spacing = 1.75
    p.paragraph_format.first_line_indent = Cm(0.74)
    p.paragraph_format.space_after = Pt(6)
    run = p.add_run(q(text))
    run.font.size = Pt(11)
    run.font.name = '宋体'
    return p

def add_bullet(doc, text):
    p = doc.add_paragraph(q(text), style='List Bullet')
    p.paragraph_format.line_spacing = 1.6
    for r in p.runs:
        r.font.size = Pt(10.5)

def add_table(doc, headers, rows):
    t = doc.add_table(rows=1+len(rows), cols=len(headers))
    t.style = 'Light Grid Accent 1'
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = q(h)
        for p in c.paragraphs:
            for r in p.runs:
                r.bold = True
                r.font.size = Pt(10)
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            c = t.rows[ri+1].cells[ci]
            c.text = q(str(val))
            for p in c.paragraphs:
                for r in p.runs:
                    r.font.size = Pt(10)
    doc.add_paragraph("")

def save(doc, filename):
    path = os.path.join(OUT_DIR, filename)
    doc.save(path)
    print(f"  OK: {filename}")

